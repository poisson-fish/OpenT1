#include <opent1/console/tag_dictionary.hpp>
#include <opent1/core/stream_io.hpp>

namespace opent1 {
namespace {
std::string_view cText(std::string_view text) noexcept {
    return text.substr(0, text.find('\0'));
}
}

bool TagDictionary::addEntry(Int32 id, std::string_view define, std::string_view text) {
    if (id <= 0 || byId_.contains(id) || defineToId(define) != 0) {
        return false;
    }
    // Intern both strings before publishing either index. Pointer hashing uses
    // the native pointer type; no legacy pointer-to-32-bit conversion remains.
    const auto key = strings_.insert(define);
    const auto value = strings_.insert(text, true);
    const auto entry = byId_.emplace(id, Entry{key, value}).first;
    try {
        byDefine_.emplace(key, id);
    } catch (...) {
        byId_.erase(entry);
        throw;
    }
    return true;
}

Int32 TagDictionary::defineToId(std::string_view define) const noexcept {
    const auto entry = byDefine_.find(strings_.lookup(define));
    return entry == byDefine_.end() ? 0 : entry->second;
}

std::optional<std::string_view>
TagDictionary::defineToString(std::string_view define) const noexcept {
    return idToString(defineToId(define));
}

std::optional<std::string_view> TagDictionary::idToString(Int32 id) const noexcept {
    const auto entry = byId_.find(id);
    return entry == byId_.end() ? std::nullopt : std::optional(entry->second.text);
}

std::optional<std::string_view> TagDictionary::idToDefine(Int32 id) const noexcept {
    const auto entry = byId_.find(id);
    return entry == byId_.end() ? std::nullopt : std::optional(entry->second.define);
}

void TagDictionary::findIDs(std::vector<Int32>& out, Int32 minId, Int32 maxId) const {
    std::ranges::for_each(byId_, [&](const auto& entry) {
        if (entry.first > minId && entry.first < maxId) {
            out.push_back(entry.first);
        }
    });
    std::ranges::sort(out);
}

void TagDictionary::findStrings(std::vector<Int32>& out, std::string_view pattern) const {
    std::ranges::for_each(byId_, [&](const auto& entry) {
        if (match(pattern, entry.second.text)) {
            out.push_back(entry.first);
        }
    });
    std::ranges::sort(out);
}

void TagDictionary::findDefines(std::vector<Int32>& out, std::string_view pattern) const {
    std::ranges::for_each(byId_, [&](const auto& entry) {
        if (match(pattern, entry.second.define)) {
            out.push_back(entry.first);
        }
    });
    std::ranges::sort(out);
}

bool TagDictionary::match(std::string_view pattern, std::string_view text) noexcept {
    pattern = cText(pattern);
    text = cText(text);
    std::size_t p = 0, t = 0, star = std::string_view::npos, retry = 0;
    // Iterative glob state machine: retry only the most recent '*'. This avoids
    // the original exponential recursive call tree and unbounded stack use.
    while (t < text.size()) {
        if (p < pattern.size() && pattern[p] == '*') {
            star = p++;
            retry = t;
        } else if (p < pattern.size() && (pattern[p] == '?' || pattern[p] == text[t])) {
            ++p;
            ++t;
        } else if (star != std::string_view::npos) {
            p = star + 1;
            t = ++retry;
        } else {
            return false;
        }
    }
    return pattern.substr(p).find_first_not_of('*') == std::string_view::npos;
}

bool TagDictionary::writeHeader(StreamIO& stream, UInt32 guardId) const {
    const auto write = [&](std::string_view text) {
        return stream.writeBytes(std::as_bytes(std::span(text.data(), text.size())));
    };
    const auto guard = std::format("_TD{:010}_H_", guardId);
    return stream.getStatus() == STRM_OK &&
           write(std::format(
               "// Auto-Generated by TagDictionary class\r\n\r\n#ifndef {}\r\n#define {}\r\n\r\n",
               guard,
               guard)) &&
           std::ranges::all_of(byId_,
                               [&](const auto& entry) {
                                   return write(std::format(
                                       "#define {} ({})\r\n", entry.second.define, entry.first));
                               }) &&
           write(std::format("\r\n#endif // {}\r\n", guard)) && stream.getStatus() == STRM_OK;
}
} // namespace opent1
