Fix16 m_AngleX_cos(AngleX angle) noexcept {
    Int32 eax = static_cast<Int32>(angle);
    // sar eax, 4; adc eax, 0 (rounds using bit 3 shifted out)
    const Int32 carry = (eax >> 3) & 1;
    eax = (eax >> 4) + carry;
    if (eax < 0) {
        eax = -eax;
    }

    if (eax < 0x400) {
        return static_cast<Fix16>(static_cast<Int32>(kCosTab[static_cast<std::size_t>(eax)]) << 2);
    }

    eax = 0x800 - eax;
    return -static_cast<Fix16>(static_cast<Int32>(kCosTab[static_cast<std::size_t>(eax)]) << 2);
}

Fix16 m_AngleX_sin(AngleX angle) noexcept {
    const auto shifted =
        std::bit_cast<AngleX>(static_cast<UInt16>(static_cast<UInt16>(angle) - 0x4000U));
    return m_AngleX_cos(shifted);
}

void m_AngleX_sincos(AngleX angle, Fix16& sine, Fix16& cosine) noexcept {
    const auto sinValue = m_AngleX_sin(angle);
    cosine = m_AngleX_cos(angle);
    sine = sinValue;
}

AngleX m_asin_(Fix16 x) {
    OPENT1_ASSERT_FATAL(x >= -65536 && x <= 65536, "Fixed asin domain error");
    const Int32 sign = (x < 0) ? -1 : 0;
    Int32 ax = (x ^ sign) - sign;

    const Int32 c1 = (ax >> 3) & 1;
    ax = (ax >> 4) + c1;

    Int32 res = 0;
    if (ax > (448 * 8 - 1)) {
        res = static_cast<Int32>(kAsinTab[static_cast<std::size_t>(ax - 448 * 7)]);
    } else {
        const Int32 c2 = (ax >> 2) & 1;
        ax = (ax >> 3) + c2;
        res = static_cast<Int32>(kAsinTab[static_cast<std::size_t>(ax)]);
    }

    res = (res ^ sign) - sign;
    return static_cast<AngleX>(res);
}

AngleX m_acos_(Fix16 x) {
    return std::bit_cast<AngleX>(
        static_cast<UInt16>(static_cast<Int32>(kAngleXHalfPi) - m_asin_(x)));
}

AngleX m_atan_(Int32 deltax, Int32 deltay) {
    OPENT1_ASSERT_FATAL(deltax != std::numeric_limits<Int32>::min() &&
                            deltay != std::numeric_limits<Int32>::min(),
                        "Fixed atan magnitude overflow");
    const auto ratioIndex = [](UInt32 smaller, UInt32 larger) {
        const UInt64 shifted = static_cast<UInt64>(smaller) << 9U;
        // The original ADD to EAX does not propagate carry into EDX.
        const UInt64 numerator = (shifted & 0xFFFFFFFF00000000ULL) |
                                 static_cast<UInt32>(static_cast<UInt32>(shifted) + (larger >> 1U));
        return static_cast<UInt32>(numerator / larger);
    };
    const Int32 signX = (deltax < 0) ? -1 : 0;
    UInt32 absX = static_cast<UInt32>((deltax ^ signX) - signX);

    const Int32 signY = (deltay < 0) ? -1 : 0;
    UInt32 absY = static_cast<UInt32>((deltay ^ signY) - signY);

    Int32 angle14 = 0;
    if (absY != 0U) {
        if (absY <= absX) {
            const UInt32 idx = ratioIndex(absY, absX);
            if (idx != 0U) {
                angle14 = static_cast<Int32>((idx << 2U) + kAtanTab[idx]);
            }
        } else {
            const UInt32 idx = ratioIndex(absX, absY);
            if (idx != 0U) {
                angle14 = static_cast<Int32>((idx << 2U) + kAtanTab[idx]);
            }
            angle14 = 4096 - angle14;
        }
    }

    if (signX < 0) {
        angle14 = 8192 - angle14;
    }
    if (signY < 0) {
        angle14 = 16384 - angle14;
    }

    return std::bit_cast<AngleX>(static_cast<UInt16>(static_cast<UInt32>(angle14) << 2U));
}

AngleF m_reduce(AngleF a) noexcept {
    RealF temp = m_AngleF_reduce(a);
    if (temp < 0.0f) {
        temp += kRealF2Pi;
    }
    return temp;
}

AngleD m_reduce(AngleD a) noexcept {
    RealD temp = m_AngleD_reduce(a);
    if (temp < 0.0) {
        temp += kRealD2Pi;
    }
    return temp;
}

