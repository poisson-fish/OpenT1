"""Validate repo-owned wiki sources, export them, or publish with Git credentials."""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PAGES = ROOT / "docs" / "wiki"
REPOSITORY = "https://github.com/poisson-fish/OpenT1"


def command_index() -> str:
    registrations: dict[str, list[str]] = {}
    # Literal registrations only. Loops, wrappers and script-defined functions
    # are deliberately excluded instead of pretending this is a runtime API dump.
    pattern = re.compile(r'\b(?:addCommand|scopedCommand)\s*\(\s*[^,]+,\s*"([^"\n]+)"')
    for path in sorted((ROOT / "src").rglob("*.cpp")):
        source = path.read_text(encoding="utf-8")
        for match in pattern.finditer(source):
            name = match[1]
            if not re.fullmatch(r"[\w:]+", name):
                continue
            line = source.count("\n", 0, match.start()) + 1
            location = f"{path.relative_to(ROOT).as_posix()}#L{line}"
            registrations.setdefault(name, []).append(location)
    text = ("# Native command index\n\n"
            "Generated by `python tools/sync_wiki.py --write-index`. Entries are literal "
            "native command registrations found in the current source. This is a source "
            "navigation index, not a complete runtime API or a promise that a command is "
            "available in every console/world. Registrations assembled in loops, wrapper "
            "tables, and functions defined by installation/mod scripts are not enumerated. "
            "Follow the implementation for argument validation, return values and world "
            "requirements. See [the reference](Scripting-reference.md) first.\n\n"
            "| Command | Native registration |\n| --- | --- |\n")
    for name, locations in sorted(registrations.items(), key=lambda item: item[0].lower()):
        links = ", ".join(f"[{p.split('#')[0]}]({REPOSITORY}/blob/main/{p})" for p in locations)
        text += f"| `{name}` | {links} |\n"
    return text


def check_pages() -> None:
    expected = command_index()
    if not (PAGES / "Command-index.md").exists() or (PAGES / "Command-index.md").read_text(encoding="utf-8") != expected:
        raise ValueError("Command index is stale; run python tools/sync_wiki.py --write-index")
    pages = {p.name for p in PAGES.glob("*.md")}
    required = {"Home.md", "Getting-started.md", "Game-modding.md", "Scripting-reference.md",
                "Scripting-examples.md", "Source-modding.md", "Releasing.md", "_Sidebar.md"}
    if not required <= pages:
        raise ValueError(f"Missing wiki pages: {sorted(required - pages)}")
    for path in PAGES.glob("*.md"):
        for target in re.findall(r"\]\(([^)\s]+)\)", path.read_text(encoding="utf-8")):
            if target.startswith(("http:", "https:", "mailto:", "#")):
                continue
            name = target.split("#", 1)[0]
            if name not in pages:
                raise ValueError(f"{path.name}: broken wiki link {target}")


def export(destination: Path) -> None:
    check_pages()
    destination.mkdir(parents=True, exist_ok=True)
    for page in PAGES.glob("*.md"):
        text = page.read_text(encoding="utf-8")
        # Wiki page URLs have no .md suffix; keep repo/package links readable too.
        text = re.sub(r"(\]\()([A-Za-z0-9_-]+)\.md(?=[)#])", r"\1\2", text)
        (destination / page.name).write_text(text, encoding="utf-8", newline="\n")


def publish(repository: str, generated_pages: dict[str, str] | None = None) -> None:
    if not re.fullmatch(r"[\w.-]+/[\w.-]+", repository):
        raise ValueError("Expected owner/repository")
    with tempfile.TemporaryDirectory(prefix="opent1-wiki-") as temporary:
        clone = Path(temporary) / "wiki"
        # gh supplies existing credentials without putting a token in the URL.
        git = ["git", "-c", "credential.helper=", "-c", "credential.helper=!gh auth git-credential"]
        subprocess.run([*git, "clone", f"https://github.com/{repository}.wiki.git", str(clone)], check=True)
        export(clone)
        page_names = [p.name for p in PAGES.glob("*.md")]
        for name, content in (generated_pages or {}).items():
            if not re.fullmatch(r"[A-Za-z0-9_-]+\.md", name) or name in page_names:
                raise ValueError(f"Invalid or canonical generated page: {name}")
            (clone / name).write_text(content, encoding="utf-8", newline="\n")
            page_names.append(name)
        subprocess.run(["git", "add", "--", *page_names], cwd=clone, check=True)
        if subprocess.run(["git", "diff", "--cached", "--quiet"], cwd=clone).returncode == 0:
            print("Wiki already matches repository documentation.")
            return
        subprocess.run(["git", "-c", "user.name=github-actions[bot]", "-c",
                        "user.email=41898282+github-actions[bot]@users.noreply.github.com",
                        "commit", "-m", "Publish OpenT1 documentation"], cwd=clone, check=True)
        subprocess.run([*git, "push", "origin", "HEAD"], cwd=clone, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--write-index", action="store_true")
    parser.add_argument("--destination", type=Path)
    parser.add_argument("--publish", metavar="OWNER/REPOSITORY")
    args = parser.parse_args()
    if args.write_index:
        (PAGES / "Command-index.md").write_text(command_index(), encoding="utf-8", newline="\n")
    check_pages()
    if args.destination:
        export(args.destination)
    if args.publish:
        publish(args.publish)


if __name__ == "__main__":
    main()
